from datetime import datetime, timezone
from typing import Dict, List
from .risk_engine import ResearchAssessment

CODE_SYSTEM = "https://example.org/fhir/CodeSystem/pediatric-vision-research"


def patient_resource(record: Dict) -> Dict:
    return {
        "resourceType": "Patient",
        "id": record["patient_id"],
        "active": True,
        "identifier": [{
            "system": "https://example.org/research/patient-id",
            "value": record["patient_id"],
        }],
        "name": [{"use": "official", "family": "Synthetic", "given": [record.get("given_name", "Child")]}],
        "gender": record.get("gender", "unknown"),
        "birthDate": record.get("birth_date"),
    }


def observation_resources(record: Dict) -> List[Dict]:
    observations = []
    for key, value in record.items():
        if key in {
            "family_history_strabismus_or_amblyopia",
            "prematurity_or_low_birth_weight",
            "clinician_observed_alignment_concern",
            "prior_vision_screen_concern",
            "caregiver_visual_behavior_concern",
            "developmental_or_neurologic_risk_context",
        } and value is not None:
            observations.append({
                "resourceType": "Observation",
                "id": f"{record['patient_id']}-{key.replace('_','-')}",
                "status": "final",
                "code": {
                    "coding": [{"system": CODE_SYSTEM, "code": key}],
                    "text": key.replace("_", " "),
                },
                "subject": {"reference": f"Patient/{record['patient_id']}"},
                "valueBoolean": bool(value),
                "note": [{"text": "Synthetic research input; not a clinical observation."}],
            })
    return observations


def risk_assessment_resource(assessment: ResearchAssessment, basis_refs: List[str]) -> Dict:
    qualitative = assessment.research_priority if not assessment.abstained else "indeterminate"
    resource = {
        "resourceType": "RiskAssessment",
        "id": f"ra-{assessment.patient_id}",
        "status": "final",
        "subject": {"reference": f"Patient/{assessment.patient_id}"},
        "occurrenceDateTime": datetime.now(timezone.utc).isoformat(),
        "basis": [{"reference": ref} for ref in basis_refs],
        "prediction": [{
            "outcome": {
                "coding": [{
                    "system": CODE_SYSTEM,
                    "code": "research-review-priority",
                    "display": "Research review priority"
                }],
                "text": "Research-only review priority; not disease risk."
            },
            "qualitativeRisk": {
                "coding": [{"system": CODE_SYSTEM, "code": qualitative}],
                "text": qualitative,
            },
            "rationale": " | ".join(assessment.rationale),
        }],
        "note": [{"text": assessment.disclaimer}],
    }
    return resource


def referral_service_request(record: Dict, assessment: ResearchAssessment) -> Dict:
    """Create a proposed workflow artifact only; it is never an actual referral order."""
    return {
        "resourceType": "ServiceRequest",
        "id": f"research-referral-{assessment.patient_id}",
        "status": "draft",
        "intent": "proposal",
        "priority": "routine",
        "code": {
            "coding": [{
                "system": CODE_SYSTEM,
                "code": "specialist-review-proposal",
                "display": "Specialist review proposal"
            }],
            "text": "Research workflow proposal for clinician consideration"
        },
        "subject": {"reference": f"Patient/{record['patient_id']}"},
        "reasonCode": [{
            "coding": [{"system": CODE_SYSTEM, "code": assessment.research_priority}],
            "text": "Generated by a non-clinical research prototype"
        }],
        "note": [{
            "text": "Draft/proposal only. This resource must not be interpreted as a clinical referral order."
        }],
    }


def build_bundle(record: Dict, assessment: ResearchAssessment) -> Dict:
    patient = patient_resource(record)
    observations = observation_resources(record)
    basis_refs = [f"Observation/{o['id']}" for o in observations]
    risk = risk_assessment_resource(assessment, basis_refs)

    resources = [patient, *observations, risk]
    if assessment.research_priority == "high-review-priority" and not assessment.abstained:
        resources.append(referral_service_request(record, assessment))

    return {
        "resourceType": "Bundle",
        "type": "collection",
        "entry": [{"resource": r} for r in resources],
    }
